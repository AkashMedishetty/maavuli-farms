/**
 * Print the AiSensy setup checklist: every WhatsApp template to submit and every API
 * campaign to create, straight from lib/notify/templates.ts, so the dashboard and
 * the code cannot drift.
 *
 *   pnpm aisensy:campaigns                 (English only — the default AISENSY_LANGUAGES)
 *   pnpm aisensy:campaigns --lang en,te    (include the Telugu set)
 *   pnpm aisensy:campaigns --md > docs/AISENSY-CAMPAIGNS.md
 *
 * For each one: the template name and category to submit, the body with Meta's
 * positional {{1}}, {{2}}… placeholders IN THE ORDER the platform fills them, sample
 * values for Meta's review, and the API campaign name the platform will call.
 * AiSensy rejects a call whose parameter count differs from the campaign's template,
 * so the order and count here are load-bearing.
 */
import { TEMPLATES, NEEDS_NATIVE_REVIEW, type RenderableTemplate } from '../lib/notify/templates.ts';
import { campaignNameFor } from '../lib/notify/providers/aisensy.ts';
import type { Lang } from '../lib/models.ts';

const args = process.argv.slice(2);
const md = args.includes('--md');
const langArg = args.find(a => a.startsWith('--lang='))?.slice('--lang='.length) ?? (args.includes('--lang') ? args[args.indexOf('--lang') + 1] : undefined);
const langs = (langArg ?? process.env.AISENSY_LANGUAGES ?? 'en').split(',').map(s => s.trim()).filter((l): l is Lang => l === 'en' || l === 'te');
if (!langs.includes('en')) langs.unshift('en');

const prefix = (process.env.AISENSY_CAMPAIGN_PREFIX ?? '').trim();
const cfg = { languages: langs, overrides: {} as Record<string, string>, prefix };

/** Realistic sample values for Meta's template review. */
const SAMPLE: Record<string, string> = {
  name: 'Anitha',
  plan: 'Cow milk, 1 litre a day, 3 months',
  startDate: 'Fri 13 Nov',
  endDate: 'Wed 10 Feb',
  amount: '₹9,832.50',
  date: 'Sat 14 Nov',
  window: '5:30–8:00 AM',
  time: '6:42 AM',
  resolution: 'One day has been added to the end of your plan',
  reason: 'the gate was locked',
  dates: 'Sat 14 Nov, Sun 15 Nov',
  lastDate: 'Fri 20 Nov',
  refund: '₹1,377.50 to your original payment method',
  link: 'https://maavulifarmmilk.com/account',
  daysLeft: '3',
  litres: '1 L',
  kind: 'cow',
  status: 'Resolved',
  note: 'We have added ₹50 credit to your account.',
  code: '482913',
};

/** Same copy with Meta's positional placeholders, in the platform's param order. */
function positional(template: RenderableTemplate, lang: Lang): string {
  const def = TEMPLATES[template];
  return def.params.reduce((acc, key, i) => acc.replaceAll(`{{${key}}}`, `{{${i + 1}}}`), def.body[lang] ?? def.body.en);
}

interface Row {
  campaign: string;
  template: string;
  category: string;
  lang: Lang;
  header: string;
  body: string;
  params: string;
  samples: string;
}

const rows: Row[] = [];
for (const lang of langs) {
  for (const [name, def] of Object.entries(TEMPLATES) as [RenderableTemplate, (typeof TEMPLATES)[RenderableTemplate]][]) {
    const variants = name === 'delivered_today' ? [false, true] : [false];
    for (const withImage of variants) {
      const isAuth = def.category === 'authentication';
      rows.push({
        campaign: campaignNameFor(name, lang, cfg, { withImage }),
        template: `${def.metaName}${withImage ? '_photo' : ''}`,
        category: isAuth ? 'Authentication' : 'Utility',
        lang,
        header: withImage ? 'Image (the doorstep photo)' : isAuth ? '— (Authentication: fixed body + Copy code button)' : 'None',
        body: isAuth ? '(fixed by Meta) {{1}} is your verification code…' : positional(name, lang),
        params: def.params.map((p, i) => `{{${i + 1}}} ${p}`).join(', ') || '—',
        samples: def.params.map(p => SAMPLE[p] ?? `<${p}>`).join(' | ') || '—',
      });
    }
  }
}

if (md) {
  console.log('# AiSensy campaigns to create\n');
  console.log(`Generated by \`pnpm aisensy:campaigns --md\` from lib/notify/templates.ts. Languages: ${langs.join(', ')}.\n`);
  console.log('For each row: (1) submit the template in AiSensy → Templates with this name, category, language and body; (2) once approved, create an **API campaign** with exactly the campaign name, attach the template, and set it **Live**.\n');
  if (langs.includes('te') && NEEDS_NATIVE_REVIEW) console.log('> The Telugu copy is a machine draft. Have a native speaker review it before submitting.\n');
  console.log('| # | API campaign name | Template | Category | Lang | Header | Body (Meta placeholders) | Params, in order | Sample values |');
  console.log('|---|---|---|---|---|---|---|---|---|');
  rows.forEach((r, i) => console.log(`| ${i + 1} | \`${r.campaign}\` | \`${r.template}\` | ${r.category} | ${r.lang} | ${r.header} | ${r.body.replace(/\|/g, '\\|')} | ${r.params} | ${r.samples.replace(/\|/g, '/')} |`));
} else {
  console.log(`AiSensy campaigns to create (${rows.length}), languages: ${langs.join(', ')}\n`);
  rows.forEach((r, i) => {
    console.log(`${String(i + 1).padStart(2)}. campaign  ${r.campaign}`);
    console.log(`    template  ${r.template}  ·  ${r.category}  ·  ${r.lang}  ·  header: ${r.header}`);
    console.log(`    body      ${r.body}`);
    console.log(`    params    ${r.params}`);
    console.log(`    samples   ${r.samples}\n`);
  });
}
